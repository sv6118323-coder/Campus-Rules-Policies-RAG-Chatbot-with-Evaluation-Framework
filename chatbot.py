GROQ_API_KEY = os.getenv("GROQ_API_KEY")

# -------------------------------------------------------
# STEP 2: LOAD THE DATABASE
# -------------------------------------------------------
print("📂 Loading database...")
embeddings = SentenceTransformerEmbeddings(
    model_name="all-MiniLM-L6-v2"
)
vectordb = Chroma(
    persist_directory="./campus_db",
    embedding_function=embeddings
)
print("✅ Database loaded!")

# -------------------------------------------------------
# STEP 3: CONNECT TO GROQ (LLaMA 3 Model)
# -------------------------------------------------------
# -------------------------------------------------------
# STEP 3: CONNECT TO GROQ (LLaMA 3 Model)
# -------------------------------------------------------
client = Groq(api_key=GROQ_API_KEY)
print("🤖 Connected to Groq API!")


# -------------------------------------------------------
# 🆕 NEW FUNCTION: evaluate_answer()
# This is the core of the Evaluation Framework
# It scores the chatbot's answer on 3 metrics:
#   1. Faithfulness  - Did the answer come from the retrieved rules?
#   2. Relevance     - Were the right rules retrieved for this question?
#   3. Confidence    - How confident is the model about its answer?
# -------------------------------------------------------
def evaluate_answer(question, context, answer):
    """
    Evaluates the quality of a RAG answer using LLaMA itself as a judge.

    Parameters:
        question (str): The student's original question
        context  (str): The retrieved chunks from ChromaDB
        answer   (str): The answer generated by the chatbot

    Returns:
        dict: scores and feedback for each metric
    """

    eval_prompt = f"""You are an evaluation system for a RAG (Retrieval-Augmented Generation) chatbot.
Your job is to score the chatbot's answer on 3 metrics.

QUESTION ASKED:
{question}

RETRIEVED CONTEXT (rules fetched from database):
{context}

CHATBOT ANSWER:
{answer}

Score each metric from 0 to 10 and give a short reason.
Reply ONLY in this exact format, nothing else:

FAITHFULNESS: <score>/10 | <one line reason>
RELEVANCE: <score>/10 | <one line reason>
CONFIDENCE: <score>/10 | <one line reason>
HALLUCINATION: <YES or NO> | <one line reason>

Definitions:
- FAITHFULNESS: Is the answer fully supported by the retrieved context? (10 = fully grounded, 0 = made up)
- RELEVANCE: Did the retrieved context actually match what the question needed? (10 = perfect match, 0 = wrong rules fetched)
- CONFIDENCE: How clearly and confidently is the answer stated? (10 = very clear and direct, 0 = vague/uncertain)
- HALLUCINATION: Did the answer include ANY information NOT present in the retrieved context?
"""

    eval_response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {"role": "user", "content": eval_prompt}
        ],
        temperature=0.0,  # 0 = fully deterministic for evaluation
        max_tokens=300
    )

    raw_eval = eval_response.choices[0].message.content

    # --- Parse the scores from the LLM's response ---
    scores = {
        "faithfulness": "N/A",
        "relevance": "N/A",
        "confidence": "N/A",
        "hallucination": "N/A",
        "raw": raw_eval  # keep full text for display
    }

    for line in raw_eval.strip().split("\n"):
        if line.startswith("FAITHFULNESS:"):
            scores["faithfulness"] = line.replace("FAITHFULNESS:", "").strip()
        elif line.startswith("RELEVANCE:"):
            scores["relevance"] = line.replace("RELEVANCE:", "").strip()
        elif line.startswith("CONFIDENCE:"):
            scores["confidence"] = line.replace("CONFIDENCE:", "").strip()
        elif line.startswith("HALLUCINATION:"):
            scores["hallucination"] = line.replace("HALLUCINATION:", "").strip()

    return scores


# -------------------------------------------------------
# MAIN FUNCTION: ask_chatbot()
# ✅ UPDATED: Now returns both answer AND evaluation scores
# -------------------------------------------------------
def ask_chatbot(question, conversation_history=None):
    """
    Answers a question using campus rules AND evaluates the answer quality.

    Parameters:
        question (str): The student's question
        conversation_history (list): Previous chat messages

    Returns:
        tuple: (answer_text, eval_scores)
               answer_text = the chatbot's answer (str)
               eval_scores = dict with faithfulness, relevance, confidence scores
    """

    # --- STEP A: Retrieve relevant rules from ChromaDB ---
    results = vectordb.similarity_search(question, k=3)
    context = "\n\n".join([result.page_content for result in results])

    # --- STEP B: Generate answer using LLaMA ---
    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {
                "role": "system",
                "content": f"""You are a helpful and friendly campus assistant 
for an institute. Your job is to answer student questions about 
campus rules and policies.

IMPORTANT RULES FOR YOU:
- Answer ONLY based on the campus rules given below
- If the answer is not in the rules, say: 
  "I don't have that information. Please contact the admin office."
- Keep answers short and clear
- Be friendly and helpful in tone

CAMPUS RULES (use only this to answer):
{context}"""
            },
            {
                "role": "user",
                "content": question
            }
        ],
        temperature=0.3,
        max_tokens=500
    )

    answer = response.choices[0].message.content

    # --- STEP C: 🆕 Evaluate the answer ---
    eval_scores = evaluate_answer(question, context, answer)

    # Return both answer and scores
    # app.py will use answer for chat display
    # app.py will use eval_scores to show the evaluation panel
    return answer, eval_scores


